import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { ThemeProvider } from "@/components/theme-provider";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: {
    default: "codeagent",
    template: "%s · codeagent",
  },
  description:
    "A coding agent with a real in-browser development environment: WebContainer workspace, tool-using chat, restorable snapshots, and GitHub push.",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      {/*
        ThemeProvider must live *inside* <body>. It injects a blocking inline
        script that reads localStorage before paint; wrapping <body> instead
        makes that script a direct child of <html>, which is invalid HTML and
        triggers a hydration error plus a possible flash of the wrong theme.
      */}
      <body className="min-h-full flex flex-col">
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem
          disableTransitionOnChange
        >
          {children}
        </ThemeProvider>
      </body>
    </html>
  );
}
